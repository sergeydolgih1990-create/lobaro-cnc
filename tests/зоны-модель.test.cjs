// node tests/зоны-модель.test.cjs
const assert=require('node:assert/strict'), fs=require('node:fs'), vm=require('node:vm');
const path=require('node:path').join(__dirname,'../редактор-зон-модель.js');
assert.ok(fs.existsSync(path),'Модуль постоянных номеров зон ещё не создан');
const box={}; vm.runInNewContext(fs.readFileSync(path,'utf8'),box);
const model=box.ZoneModel.create();
const a=model.add({x0:20,x1:10,y0:50,y1:30});
assert.equal(a.id,1); assert.equal(a.x0,10); assert.equal(a.y0,30);
model.remove(1); const b=model.add({x0:0,x1:4,y0:0,y1:3});
assert.equal(b.id,2,'Удалённые номера повторно не используются');
assert.equal(model.snapshot().maxId,2);
model.update(2,{x0:2,x1:9,y0:3,y1:8,note:'ухо'});
const saved=model.snapshot(); assert.equal(saved.rects[0].note,'ухо');
saved.rects[0].x0=900; assert.equal(model.snapshot().rects[0].x0,2,'Снимок независим');
const restored=box.ZoneModel.create(model.snapshot()); assert.equal(restored.add({x0:0,x1:1,y0:0,y1:1}).id,3);
assert.throws(()=>model.add({x0:NaN,x1:3,y0:0,y1:2}));
assert.throws(()=>model.add({x0:1,x1:1,y0:0,y1:2}));
assert.throws(()=>box.ZoneModel.create({maxId:2,rects:[{id:2,x0:0,x1:1,y0:0,y1:1},{id:2,x0:0,x1:1,y0:0,y1:1}]}));
assert.throws(()=>box.ZoneModel.create({maxId:1,rects:[{id:4,x0:0,x1:1,y0:0,y1:1}]}));
const full=box.ZoneModel.create();
for(let i=0;i<1000;i++)full.add({x0:0,x1:1,y0:0,y1:1});
const fullBefore=JSON.stringify(full.snapshot());
assert.throws(()=>full.add({x0:0,x1:1,y0:0,y1:1}),/1000/,'Создание соблюдает предел загрузки');
assert.equal(JSON.stringify(full.snapshot()),fullBefore,'Отклонение не меняет карту');
const exhausted=box.ZoneModel.create({maxId:Number.MAX_SAFE_INTEGER,rects:[]});
assert.throws(()=>exhausted.add({x0:0,x1:1,y0:0,y1:1}),/номера/);
assert.equal(exhausted.snapshot().rects.length,0);
assert.equal(exhausted.snapshot().maxId,Number.MAX_SAFE_INTEGER);
console.log('PASS: постоянные номера, нормализация, сохранение, независимые снимки, защита повреждённых данных');
